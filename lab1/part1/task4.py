"""
4. Дана строка в виде случайной последовательности чисел от 0 до 9
Требуется создать словарь, который в качестве ключей будет
принимать данные числа (т. е. ключи будут типом int), а в качестве
значений – количество этих чисел в имеющейся последовательности. –
2 балла
"""
import random

s = "".join(str(random.randint(0, 9)) for _ in range(random.randint(5, 20)))
print(s)
d = {}
for ch in s:
    if ch.isdigit():
        key = int(ch)
        d[key] = d.get(key, 0) + 1
print(d)
